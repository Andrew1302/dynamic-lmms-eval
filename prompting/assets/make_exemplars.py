"""Render the few-shot exemplar assets for cot_fewshot_img_v1.

Exemplars are generated by the REAL benchmark generator, at a seed base far
outside the evaluation seed space, so a worked example can never be a graph the
model is later scored on.

Eval seeds are ``args.seed + i*1000 + crc32(task)%1000`` with args.seed=42
(tools/prepare_dynamic_graph_benchmark.py), i.e. below ~10^7 for any realistic
N. EXEMPLAR_SEED_BASE sits three orders of magnitude above that.

Run (house style: a throwaway env, no venv mutated):

    uv run --no-project --with matplotlib --with networkx --with pillow \
           --with pyyaml --with scipy --with adjustText \
           python prompting/assets/make_exemplars.py

It writes <task>_<variant>_ex<k>.{png,yaml}. The `worked_solution` field is
emitted as a TODO marker: the reasoning narrative must be written by hand
against the rendered picture, because a wrong exemplar silently poisons every
few-shot run. `test_exemplars_authored` fails while any TODO remains.
"""

from __future__ import annotations

import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
REPO_ROOT = HERE.parents[1]
DATASET_ROOT = REPO_ROOT.parent / "dynamic-dataset"

EXEMPLAR_SEED_BASE = 900_000_000
DIFFICULTY = "easy"  # short, legible worked solutions
VARIANTS = ("direct", "disguise")

# Seeds are pinned per task rather than taken blindly from the base, because an
# exemplar has to be *readable*: these were each rendered and inspected. The
# first coloring candidate (BASE+1) was rejected - its map disguise placed the
# labels for regions 0/5 and 1/4 on top of each other. Answers are also chosen
# to differ between a task's two exemplars, so the demonstration never teaches
# a constant answer.
EXEMPLAR_SEEDS = {
    "coloring": (EXEMPLAR_SEED_BASE + 10, EXEMPLAR_SEED_BASE + 15),  # chi = 3, 4
    "directed_connectivity": (EXEMPLAR_SEED_BASE, EXEMPLAR_SEED_BASE + 1),  # Yes, No
    "shortest_path": (EXEMPLAR_SEED_BASE, EXEMPLAR_SEED_BASE + 1),  # 15, 12
}
N_EXEMPLARS = 2

TODO = "TODO: write the reasoning narrative for this exemplar by hand."


def main() -> int:
    if not DATASET_ROOT.is_dir():
        sys.exit(f"sibling dynamic-dataset repo not found at {DATASET_ROOT}")
    sys.path.insert(0, str(DATASET_ROOT))
    from src.benchmark import get_task  # noqa: E402
    from src.benchmark.rendering import RenderConfig  # noqa: E402

    cfg = RenderConfig()  # campaign defaults: numeric labels, #AED6F1, straight
    for task_name, seeds in EXEMPLAR_SEEDS.items():
        task = get_task(task_name)()
        for k, seed in enumerate(seeds):
            plain = task.generate(seed=seed, difficulty=DIFFICULTY, config=cfg)
            # Same seed => same graph; the adjacency dump is authoring material
            # for the narrative, never part of the exemplar prompt itself.
            annotated = task.generate(seed=seed, difficulty=DIFFICULTY, config=cfg, include_adjacency_list=True)
            for variant in VARIANTS:
                stem = f"{task_name}_{variant}_ex{k + 1}"
                plain[f"{variant}_image"].save(HERE / f"{stem}.png")
                existing = HERE / f"{stem}.yaml"
                solution = TODO
                if existing.exists():
                    prev = yaml.safe_load(existing.read_text(encoding="utf-8"))
                    if prev.get("seed") == seed and not str(prev.get("worked_solution", "")).startswith("TODO"):
                        solution = prev["worked_solution"]  # keep hand-authored text
                existing.write_text(
                    yaml.safe_dump(
                        {
                            "task": task_name,
                            "variant": variant,
                            "seed": seed,
                            "question": plain[f"{variant}_prompt"],
                            "answer": plain["answer"],
                            "authoring_adjacency": annotated[f"{variant}_prompt"],
                            "worked_solution": solution,
                        },
                        sort_keys=False,
                        allow_unicode=True,
                        default_flow_style=False,
                    ),
                    encoding="utf-8",
                )
                print(f"  wrote {stem}.png / .yaml  (answer={plain['answer']})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
