"""Generate the ablation/sweep job conf files under jobs/graph_benchmark/.

Each conf is a small bash-sourceable file (matching the existing format
used by ``01_deploy.sh`` / ``02_run.sh``) that exports a handful of env
vars consumed by ``examples/models/dynamic_graph_benchmark/run_eval.sh``.

Re-run this script after editing the model lists below; it overwrites
existing confs but leaves any *manually-added* confs alone.

    cd remote_execution_scripts
    python jobs/generate_graph_benchmark_jobs.py

Also emits batches/ manifests so a single ``run_batch.sh -f`` invocation
can chain all jobs in a class (standard, ablation_labels, etc.).
"""

from __future__ import annotations

import dataclasses
import os
import textwrap
from pathlib import Path

_HERE = Path(__file__).resolve().parent
_OUT_DIR = _HERE / "graph_benchmark"
_BATCH_DIR = _HERE.parent / "batches"


@dataclasses.dataclass(frozen=True)
class Model:
    short: str  # used in JOB_NAME / DATASET_DIR
    pretrained: str  # HF id


# Primary panel: small-enough to fit on the eval VMs.
MODELS_4B = [
    Model("qwen3vl_4b", "Qwen/Qwen3-VL-4B-Instruct"),
    Model("internvl35_4b", "OpenGVLab/InternVL3_5-4B"),
    Model("qwen35_4b", "Qwen/Qwen3.5-4B"),
    Model("gemma4_e2b", "google/gemma-4-E2B-it"),
]

# Larger panel: only used for the model-size ablation (n=500).
MODELS_8B = [
    Model("qwen3vl_8b", "Qwen/Qwen3-VL-8B-Instruct"),
    Model("internvl35_8b", "OpenGVLab/InternVL3_5-8B"),
    Model("llava_ov15_8b", "lmms-lab/LLaVA-OneVision-1.5-8B"),
    Model("minicpmv_2_6", "openbmb/MiniCPM-V-2_6"),
    Model("llama32_v_11b", "meta-llama/Llama-3.2-11B-Vision-Instruct"),
    Model("qwen35_9b", "Qwen/Qwen3.5-9B"),
]

# Thinking-mode SKUs (paired against their -Instruct counterparts).
MODELS_THINKING = [
    Model("qwen3vl_4b_thinking", "Qwen/Qwen3-VL-4B-Thinking"),
    Model("qwen3vl_8b_thinking", "Qwen/Qwen3-VL-8B-Thinking"),
]


STANDARD_N = 5000
ABLATION_N = 500
TASKS = "coloring directed_connectivity shortest_path"
DIFFICULTY = "medium"
DIFFICULTY_OVERRIDES = "shortest_path=easy"

# Sweep config. Node ranges cover the union of the three difficulty
# presets (3..14 across tasks). Edge values are picked to span the
# observed edge-count ranges seen in the three difficulties.
SWEEP_NODE_VALUES = "3..14"
SWEEP_NODE_SPV = 250
SWEEP_EDGE_VALUES = "3,5,8,12,18,25,35"  # log-ish, covers easy..hard
SWEEP_EDGE_SPV = 100

# Chunking. CHUNK_SIZE rows per lmms-eval invocation; sentinels under
# $RUN_DIR/chunks/ let a re-run of ./02_run.sh resume from the first
# failed/pending chunk. 0 = no chunking. Values must be even to keep
# direct/disguise pairs together (prepare bumps odd values up by 1).
# Standard 5k runs amortise model-load overhead better at higher chunk
# sizes; small ablation runs stay effectively monolithic at 500.
CHUNK_STANDARD = 500
CHUNK_ABLATION = 100
CHUNK_SWEEP = 200


_PREAMBLE = """\
# =============================================================================
# Generated by remote_execution_scripts/jobs/generate_graph_benchmark_jobs.py
# Do not edit by hand — re-run the generator instead.
# =============================================================================
"""

_FOOTER = textwrap.dedent("""\

    UPLOAD_PATHS=(
        "lmms_eval"
        "tools"
        "examples/models/dynamic_graph_benchmark"
        "pyproject.toml"
        "uv.lock"
        "setup.py"
        "README.md"
    )

    DATASET_UPLOAD_PATHS=(
        "src"
        "pyproject.toml"
        "uv.lock"
    )

    REMOTE_SETUP_CMD="uv sync && uv pip install adjustText cartopy"

    REMOTE_RUN_CMD="bash examples/models/dynamic_graph_benchmark/run_eval.sh"

    RESULT_PATHS=(
        "logs/${JOB_NAME}"
        "${DATASET_DIR}"
        "${DATASET_DIR}_images"
    )

    COMPARE_PAIRS=(
        "coloring:dynamic_graph_benchmark_coloring_direct:dynamic_graph_benchmark_coloring_disguise"
        "directed_connectivity:dynamic_graph_benchmark_directed_connectivity_direct:dynamic_graph_benchmark_directed_connectivity_disguise"
        "shortest_path:dynamic_graph_benchmark_shortest_path_direct:dynamic_graph_benchmark_shortest_path_disguise"
    )
""")


def _write_conf(
    *,
    name: str,
    description: str,
    env: dict[str, str],
) -> Path:
    """Write a single bash-sourceable conf. ``env`` keys are exported."""
    lines: list[str] = [_PREAMBLE, f"# {description}\n"]
    # Each env var as a bash assignment (sourced into the parent shell
    # via 01_deploy.sh / 02_run.sh / run_eval.sh's env contract).
    lines.append(f'JOB_NAME="{name}"\n')
    lines.append(f'DATASET_DIR="./dataset_{name}"\n')
    for k, v in env.items():
        lines.append(f'export {k}="{v}"\n')
    lines.append("export DATASET_DIR\n")
    lines.append("export JOB_NAME\n")
    lines.append(_FOOTER)

    path = _OUT_DIR / f"{name}.conf"
    # newline="\n" prevents Path.write_text from doing platform translation on
    # Windows — bash + `source` chokes on `export FOO\r` lines.
    path.write_text("".join(lines), encoding="utf-8", newline="\n")
    return path


def _standard_env(num_samples: int, chunk_size: int) -> dict[str, str]:
    return {
        "NUM_SAMPLES": str(num_samples),
        "DIFFICULTY": DIFFICULTY,
        "DIFFICULTY_OVERRIDES": DIFFICULTY_OVERRIDES,
        "TASKS": TASKS,
        "LABEL_STYLE": "numeric",
        "NODE_COLOR": "#AED6F1",
        "EDGE_STYLE": "straight",
        "INCLUDE_ADJ_MATRIX": "0",
        "CHUNK_SIZE": str(chunk_size),
    }


def main() -> None:
    _OUT_DIR.mkdir(parents=True, exist_ok=True)
    _BATCH_DIR.mkdir(parents=True, exist_ok=True)

    batches: dict[str, list[str]] = {}

    # --- Standard jobs: n=5000, defaults, 4B panel ----------------------------
    batches["standard_4b"] = []
    for m in MODELS_4B:
        name = f"graph_bench_standard_{m.short}"
        env = _standard_env(STANDARD_N, CHUNK_STANDARD)
        env["MODEL_PRETRAINED"] = m.pretrained
        _write_conf(
            name=name,
            description=f"Standard run (n={STANDARD_N}, defaults) for {m.pretrained}",
            env=env,
        )
        batches["standard_4b"].append(name)

    # --- Label-style ablation: letters + none, 4B panel, n=500 ----------------
    batches["ablation_labels"] = []
    for style in ("letters", "none"):
        for m in MODELS_4B:
            name = f"graph_bench_ablation_labels_{style}_{m.short}"
            env = _standard_env(ABLATION_N, CHUNK_ABLATION)
            env["MODEL_PRETRAINED"] = m.pretrained
            env["LABEL_STYLE"] = style
            _write_conf(
                name=name,
                description=f"Ablation: label_style={style} (n={ABLATION_N}) for {m.pretrained}",
                env=env,
            )
            batches["ablation_labels"].append(name)

    # --- Node-color ablation: alt color, 4B panel, n=500 ----------------------
    batches["ablation_color"] = []
    alt_color = "#F1948A"
    for m in MODELS_4B:
        name = f"graph_bench_ablation_color_{m.short}"
        env = _standard_env(ABLATION_N, CHUNK_ABLATION)
        env["MODEL_PRETRAINED"] = m.pretrained
        env["NODE_COLOR"] = alt_color
        _write_conf(
            name=name,
            description=f"Ablation: node_color={alt_color} (n={ABLATION_N}) for {m.pretrained}",
            env=env,
        )
        batches["ablation_color"].append(name)

    # --- Adjacency-matrix ablation: 4B panel, n=500 ---------------------------
    batches["ablation_adjmatrix"] = []
    for m in MODELS_4B:
        name = f"graph_bench_ablation_adjmatrix_{m.short}"
        env = _standard_env(ABLATION_N, CHUNK_ABLATION)
        env["MODEL_PRETRAINED"] = m.pretrained
        env["INCLUDE_ADJ_MATRIX"] = "1"
        _write_conf(
            name=name,
            description=f"Ablation: include adjacency matrix in prompt (n={ABLATION_N}) for {m.pretrained}",
            env=env,
        )
        batches["ablation_adjmatrix"].append(name)

    # --- Thinking-mode ablation: 4B+8B Qwen3-VL Thinking variants -------------
    batches["ablation_thinking"] = []
    for m in MODELS_THINKING:
        name = f"graph_bench_ablation_thinking_{m.short}"
        env = _standard_env(ABLATION_N, CHUNK_ABLATION)
        env["MODEL_PRETRAINED"] = m.pretrained
        _write_conf(
            name=name,
            description=f"Ablation: thinking-mode SKU (n={ABLATION_N}) for {m.pretrained}",
            env=env,
        )
        batches["ablation_thinking"].append(name)

    # --- Model-size ablation: 8B panel, n=500 ---------------------------------
    batches["ablation_model_size"] = []
    for m in MODELS_8B:
        name = f"graph_bench_ablation_size_{m.short}"
        env = _standard_env(ABLATION_N, CHUNK_ABLATION)
        env["MODEL_PRETRAINED"] = m.pretrained
        _write_conf(
            name=name,
            description=f"Ablation: model size, n={ABLATION_N} for {m.pretrained}",
            env=env,
        )
        batches["ablation_model_size"].append(name)

    # --- Sweep over nodes: 4B panel, 250 samples per value --------------------
    batches["sweep_nodes"] = []
    for m in MODELS_4B:
        name = f"graph_bench_sweep_nodes_{m.short}"
        env = _standard_env(
            ABLATION_N, CHUNK_SWEEP
        )  # NUM_SAMPLES ignored in sweep mode
        env["MODEL_PRETRAINED"] = m.pretrained
        env["CONSTRAINT"] = "nodes"
        env["CONSTRAINT_VALUES"] = SWEEP_NODE_VALUES
        env["SAMPLES_PER_VALUE"] = str(SWEEP_NODE_SPV)
        # Difficulty overrides don't apply in sweep mode.
        env.pop("DIFFICULTY_OVERRIDES", None)
        _write_conf(
            name=name,
            description=f"Sweep: vertex-count axis ({SWEEP_NODE_VALUES}, {SWEEP_NODE_SPV}/value) for {m.pretrained}",
            env=env,
        )
        batches["sweep_nodes"].append(name)

    # --- Sweep over edges: 4B panel, 100 samples per value --------------------
    batches["sweep_edges"] = []
    for m in MODELS_4B:
        name = f"graph_bench_sweep_edges_{m.short}"
        env = _standard_env(ABLATION_N, CHUNK_SWEEP)
        env["MODEL_PRETRAINED"] = m.pretrained
        env["CONSTRAINT"] = "edges"
        env["CONSTRAINT_VALUES"] = SWEEP_EDGE_VALUES
        env["SAMPLES_PER_VALUE"] = str(SWEEP_EDGE_SPV)
        env.pop("DIFFICULTY_OVERRIDES", None)
        _write_conf(
            name=name,
            description=f"Sweep: edge-count axis ({SWEEP_EDGE_VALUES}, {SWEEP_EDGE_SPV}/value) for {m.pretrained}",
            env=env,
        )
        batches["sweep_edges"].append(name)

    # --- Emit batch manifests -------------------------------------------------
    # load_job() takes the conf path *relative to jobs/* without the .conf
    # suffix, so for confs in graph_benchmark/ the job id is
    # "graph_benchmark/<name>".
    total = 0
    for batch_name, job_names in batches.items():
        manifest = _BATCH_DIR / f"{batch_name}.txt"
        manifest.write_text(
            "\n".join(f"graph_benchmark/{n}" for n in job_names) + "\n",
            encoding="utf-8",
            newline="\n",
        )
        total += len(job_names)
        print(f"[batch] {batch_name}: {len(job_names)} jobs -> {manifest}")

    print(
        f"\nWrote {total} conf files under {_OUT_DIR}/ and "
        f"{len(batches)} batch manifests under {_BATCH_DIR}/."
    )


if __name__ == "__main__":
    main()
