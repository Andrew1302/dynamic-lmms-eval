"""Generate the ablation/sweep job conf files under jobs/graph_benchmark/.

Each conf is a small bash-sourceable file (matching the existing format
used by ``01_deploy.sh`` / ``02_run.sh``) that exports a handful of env
vars consumed by ``examples/models/dynamic_graph_benchmark/run_eval.sh``.

Re-run this script after editing the model lists below; it overwrites
existing confs but leaves any *manually-added* confs alone.

    cd remote_execution_scripts
    python jobs/generate_graph_benchmark_jobs.py

Also emits batches/ manifests so a single ``run_batch.sh -f`` invocation
can chain all jobs in a class (standard, ablation_labels, etc.).
"""

from __future__ import annotations

import dataclasses
import os
import textwrap
from pathlib import Path

_HERE = Path(__file__).resolve().parent
_OUT_DIR = _HERE / "graph_benchmark"
_BATCH_DIR = _HERE.parent / "batches"


@dataclasses.dataclass(frozen=True)
class Model:
    short: str  # used in JOB_NAME / DATASET_DIR
    pretrained: str  # HF id


# Primary panel: small-enough to fit on the eval VMs.
# Trimmed to the three models the current campaign cares about
# (Qwen3.5-4B, InternVL3.5-4B, Gemma-4-E2B/"2B"). Add back others here.
MODELS_4B = [
    Model("internvl35_4b", "OpenGVLab/InternVL3_5-4B"),
    Model("qwen35_4b", "Qwen/Qwen3.5-4B"),
    Model("gemma4_e2b", "google/gemma-4-E2B-it"),
]


STANDARD_N = 5000
ABLATION_N = 500
# Difficulty-separated label/color ablation: n per task per difficulty. The
# ablation only needs to detect a shift, so 100/task/difficulty is enough.
ABLATION_DIFF_N = 100
TASKS = "coloring directed_connectivity shortest_path"
DIFFICULTY = "medium"
DIFFICULTY_OVERRIDES = "shortest_path=easy"

# Difficulty-separated standard runs: one job per (difficulty, model), n=500
# generations/task (→ 1500 direct + 1500 disguise rows). Each difficulty is
# pure — every task is rendered at that difficulty (no per-task override), so
# the three runs form a clean easy→medium→hard gradient.
STANDARD_DIFFICULTIES = ("easy", "medium", "hard")
STANDARD_DIFF_N = 500

# Adjacency-list ablation: same difficulty-separated layout as the standard
# runs but a lighter n=100/task (the ablation only needs to detect a shift,
# not estimate accuracy tightly). The dynamic-dataset INCLUDE_ADJ_MATRIX flag
# now renders a text adjacency *list* (see dynamic-dataset "replace adj matrix
# with adj list").
ADJLIST_DIFF_N = 100

# Sweep config. Node ranges cover the union of the three difficulty
# presets (3..14 across tasks). Edge values are picked to span the
# observed edge-count ranges seen in the three difficulties.
SWEEP_NODE_VALUES = "3..14"
SWEEP_NODE_SPV = 100
SWEEP_EDGE_VALUES = "3,5,8,12,18,25,35"  # log-ish, covers easy..hard
SWEEP_EDGE_SPV = 100

# Chunking. CHUNK_SIZE rows per lmms-eval invocation; sentinels under
# $RUN_DIR/chunks/ let a re-run of ./02_run.sh resume from the first
# failed/pending chunk. 0 = no chunking. Values must be even to keep
# direct/disguise pairs together (prepare bumps odd values up by 1).
# Standard 5k runs amortise model-load overhead better at higher chunk
# sizes; small ablation runs stay effectively monolithic at 500.
CHUNK_STANDARD = 500
CHUNK_ABLATION = 100
CHUNK_SWEEP = 200

# Thinking-vs-no-thinking ablation. n=100/task/difficulty; one arm per THINKING
# value. Thinking generations are long (max_new_tokens=4096) and slow, so the
# think arm uses a smaller chunk so a mid-run failure resumes with less lost work.
THINK_ABLATION_N = 100
CHUNK_THINK = 50

# Thinking-ablation panel — all three 4B models. Qwen3.5-4B is now included:
# its no-think arm is coerced terse by a reasoning_prompt directive (fits the
# 1024-tok answer budget) and its think arm uses vllm's native thinking-token
# budget (12288) so its heavy over-deliberation force-closes </think> instead of
# truncating the answer (was ~40% lost → ~0%). InternVL3.5 (R1 <think> prompt,
# fp8) and Gemma-4-E2B (enable_thinking, bf16) as before. Per-model thinking
# mechanism + budgets all live in run_eval.sh keyed on MODEL_PRETRAINED.
THINK_MODELS = MODELS_4B


_PREAMBLE = """\
# =============================================================================
# Generated by remote_execution_scripts/jobs/generate_graph_benchmark_jobs.py
# Do not edit by hand — re-run the generator instead.
# =============================================================================
"""

_FOOTER = textwrap.dedent("""\

    UPLOAD_PATHS=(
        "lmms_eval"
        "tools"
        "examples/models/dynamic_graph_benchmark"
        "pyproject.toml"
        "uv.lock"
        "setup.py"
        "README.md"
    )

    DATASET_UPLOAD_PATHS=(
        "src"
        "pyproject.toml"
        "uv.lock"
    )

    REMOTE_SETUP_CMD="uv sync && uv pip install adjustText cartopy"

    REMOTE_RUN_CMD="bash examples/models/dynamic_graph_benchmark/run_eval.sh"

    RESULT_PATHS=(
        "logs/${JOB_NAME}"
        "${DATASET_DIR}"
        "${DATASET_DIR}_images"
    )
""")


def _compare_pairs_block(tasks: str) -> str:
    """Build a COMPARE_PAIRS bash array covering only the job's TASKS.

    07_batch_report.sh's collect_paired_job indexes by_task_ts for *every*
    referenced pair, so a pair whose task produced no jsonl raises KeyError
    and the whole job is dropped as NO_DATA. Coloring-only jobs therefore
    must reference only the coloring pair. The spec format is uniform:
    ``<task>:dynamic_graph_benchmark_<task>_direct:..._disguise``.
    """
    lines = ["\nCOMPARE_PAIRS=("]
    for t in tasks.split():
        lines.append(
            f'    "{t}:dynamic_graph_benchmark_{t}_direct:'
            f'dynamic_graph_benchmark_{t}_disguise"'
        )
    lines.append(")\n")
    return "\n".join(lines)


def _write_conf(
    *,
    name: str,
    description: str,
    env: dict[str, str],
) -> Path:
    """Write a single bash-sourceable conf. ``env`` keys are exported."""
    lines: list[str] = [_PREAMBLE, f"# {description}\n"]
    # Each env var as a bash assignment (sourced into the parent shell
    # via 01_deploy.sh / 02_run.sh / run_eval.sh's env contract).
    lines.append(f'JOB_NAME="{name}"\n')
    lines.append(f'DATASET_DIR="./dataset_{name}"\n')
    for k, v in env.items():
        lines.append(f'export {k}="{v}"\n')
    lines.append("export DATASET_DIR\n")
    lines.append("export JOB_NAME\n")
    lines.append(_FOOTER)
    # COMPARE_PAIRS is derived from the job's TASKS so single-task jobs (e.g.
    # the coloring re-run) don't reference pairs with no data — see
    # _compare_pairs_block. TASKS defaults to all three tasks via _standard_env.
    tasks = env.get("TASKS", "coloring directed_connectivity shortest_path")
    lines.append(_compare_pairs_block(tasks))

    path = _OUT_DIR / f"{name}.conf"
    # newline="\n" prevents Path.write_text from doing platform translation on
    # Windows — bash + `source` chokes on `export FOO\r` lines.
    path.write_text("".join(lines), encoding="utf-8", newline="\n")
    return path


def _standard_env(num_samples: int, chunk_size: int) -> dict[str, str]:
    return {
        "NUM_SAMPLES": str(num_samples),
        "DIFFICULTY": DIFFICULTY,
        "DIFFICULTY_OVERRIDES": DIFFICULTY_OVERRIDES,
        "TASKS": TASKS,
        "LABEL_STYLE": "numeric",
        "NODE_COLOR": "#AED6F1",
        "EDGE_STYLE": "straight",
        "INCLUDE_ADJ_MATRIX": "0",
        "CHUNK_SIZE": str(chunk_size),
    }


def main() -> None:
    _OUT_DIR.mkdir(parents=True, exist_ok=True)
    _BATCH_DIR.mkdir(parents=True, exist_ok=True)

    batches: dict[str, list[str]] = {}

    # --- Standard jobs: difficulty-separated, n=500/task, 4B panel ------------
    # One job per (difficulty, model): graph_bench_standard_<difficulty>_<model>.
    # Ordered difficulty-major so the batch runs easy→medium→hard.
    batches["standard"] = []
    for diff in STANDARD_DIFFICULTIES:
        for m in MODELS_4B:
            name = f"graph_bench_standard_{diff}_{m.short}"
            env = _standard_env(STANDARD_DIFF_N, CHUNK_STANDARD)
            env["DIFFICULTY"] = diff
            # Pure per-difficulty: every task rendered at this difficulty.
            env.pop("DIFFICULTY_OVERRIDES", None)
            env["MODEL_PRETRAINED"] = m.pretrained
            _write_conf(
                name=name,
                description=f"Standard run (n={STANDARD_DIFF_N}/task, difficulty={diff}) for {m.pretrained}",
                env=env,
            )
            batches["standard"].append(name)

    # --- Coloring re-run: special-coloring, difficulty-separated, n=500 -------
    # The default coloring graphs (full Delaunay triangulation) have a chromatic
    # number that concentrates on 3-4, so the answer is nearly constant and the
    # signal is weak/guessable. SPECIAL_COLORING plants χ uniformly across
    # {2,3,4} (linear 2→3→4 per sample). One job per (difficulty, model),
    # coloring task only, n=500/task — mirrors the standard layout so the
    # easy→medium→hard gradient is preserved.
    batches["coloring"] = []
    for diff in STANDARD_DIFFICULTIES:
        for m in MODELS_4B:
            name = f"graph_bench_coloring_{diff}_{m.short}"
            env = _standard_env(STANDARD_DIFF_N, CHUNK_STANDARD)
            env["DIFFICULTY"] = diff
            env.pop("DIFFICULTY_OVERRIDES", None)
            env["TASKS"] = "coloring"
            env["SPECIAL_COLORING"] = "1"
            env["MODEL_PRETRAINED"] = m.pretrained
            _write_conf(
                name=name,
                description=(
                    f"Coloring re-run (special-coloring χ∈{{2,3,4}} uniform, "
                    f"n={STANDARD_DIFF_N}/task, difficulty={diff}) for {m.pretrained}"
                ),
                env=env,
            )
            batches["coloring"].append(name)

    # --- Label-style ablation: letters + none, difficulty-separated, n=100 ----
    # One job per (style, difficulty, model). Because --special-coloring yields a
    # coloring-ONLY dataset, coloring is split into its own SPECIAL_COLORING job
    # (χ∈{2,3,4} linear 2→3→4) while directed_connectivity + shortest_path share
    # a job. Together the two jobs cover all three tasks per (style, diff, model)
    # at n=ABLATION_DIFF_N/task. Mirrors the standard/coloring difficulty layout
    # so the report keeps a clean easy→medium→hard gradient per model.
    batches["ablation_labels"] = []
    batches["ablation_labels_letters"] = []
    batches["ablation_labels_none"] = []
    for style in ("letters", "none"):
        for diff in STANDARD_DIFFICULTIES:
            for m in MODELS_4B:
                # directed_connectivity + shortest_path (default coloring absent)
                name = f"graph_bench_ablation_labels_{style}_{diff}_{m.short}"
                env = _standard_env(ABLATION_DIFF_N, CHUNK_ABLATION)
                env["DIFFICULTY"] = diff
                env.pop("DIFFICULTY_OVERRIDES", None)
                env["TASKS"] = "directed_connectivity shortest_path"
                env["LABEL_STYLE"] = style
                env["MODEL_PRETRAINED"] = m.pretrained
                _write_conf(
                    name=name,
                    description=(
                        f"Ablation: label_style={style}, conn+shortest_path "
                        f"(n={ABLATION_DIFF_N}/task, difficulty={diff}) for {m.pretrained}"
                    ),
                    env=env,
                )
                batches["ablation_labels"].append(name)
                batches[f"ablation_labels_{style}"].append(name)
                # coloring only, balanced χ∈{2,3,4} (special coloring)
                cname = f"graph_bench_ablation_labels_{style}_coloring_{diff}_{m.short}"
                cenv = _standard_env(ABLATION_DIFF_N, CHUNK_ABLATION)
                cenv["DIFFICULTY"] = diff
                cenv.pop("DIFFICULTY_OVERRIDES", None)
                cenv["TASKS"] = "coloring"
                cenv["SPECIAL_COLORING"] = "1"
                cenv["LABEL_STYLE"] = style
                cenv["MODEL_PRETRAINED"] = m.pretrained
                _write_conf(
                    name=cname,
                    description=(
                        f"Ablation: label_style={style}, coloring only with "
                        f"balanced χ∈{{2,3,4}} (special-coloring), "
                        f"n={ABLATION_DIFF_N}/task, difficulty={diff}) for {m.pretrained}"
                    ),
                    env=cenv,
                )
                batches["ablation_labels"].append(cname)
                batches[f"ablation_labels_{style}"].append(cname)

    # --- Node-color ablation: alt color, difficulty-separated, n=100 ----------
    # Same split as the label ablation: conn+shortest_path in one job, coloring
    # (special, χ∈{2,3,4} linear) in another, per (difficulty, model).
    batches["ablation_color"] = []
    alt_color = "#F1948A"
    for diff in STANDARD_DIFFICULTIES:
        for m in MODELS_4B:
            name = f"graph_bench_ablation_color_{diff}_{m.short}"
            env = _standard_env(ABLATION_DIFF_N, CHUNK_ABLATION)
            env["DIFFICULTY"] = diff
            env.pop("DIFFICULTY_OVERRIDES", None)
            env["TASKS"] = "directed_connectivity shortest_path"
            env["NODE_COLOR"] = alt_color
            env["MODEL_PRETRAINED"] = m.pretrained
            _write_conf(
                name=name,
                description=(
                    f"Ablation: node_color={alt_color}, conn+shortest_path "
                    f"(n={ABLATION_DIFF_N}/task, difficulty={diff}) for {m.pretrained}"
                ),
                env=env,
            )
            batches["ablation_color"].append(name)
            cname = f"graph_bench_ablation_color_coloring_{diff}_{m.short}"
            cenv = _standard_env(ABLATION_DIFF_N, CHUNK_ABLATION)
            cenv["DIFFICULTY"] = diff
            cenv.pop("DIFFICULTY_OVERRIDES", None)
            cenv["TASKS"] = "coloring"
            cenv["SPECIAL_COLORING"] = "1"
            cenv["NODE_COLOR"] = alt_color
            cenv["MODEL_PRETRAINED"] = m.pretrained
            _write_conf(
                name=cname,
                description=(
                    f"Ablation: node_color={alt_color}, coloring only with "
                    f"balanced χ∈{{2,3,4}} (special-coloring), "
                    f"n={ABLATION_DIFF_N}/task, difficulty={diff}) for {m.pretrained}"
                ),
                env=cenv,
            )
            batches["ablation_color"].append(cname)

    # --- Adjacency-list ablation: difficulty-separated, n=100/task, 4B panel --
    # One job per (difficulty, model): graph_bench_ablation_adjlist_<diff>_<m>.
    # Pure per-difficulty (every task rendered at this difficulty, no override)
    # so the runs form a clean easy→medium→hard gradient, mirroring the
    # standard layout. INCLUDE_ADJ_MATRIX=1 now appends a text adjacency *list*
    # to the prompt (the flag name is retained for compatibility).
    batches["ablation_adjlist"] = []
    for diff in STANDARD_DIFFICULTIES:
        for m in MODELS_4B:
            name = f"graph_bench_ablation_adjlist_{diff}_{m.short}"
            env = _standard_env(ADJLIST_DIFF_N, CHUNK_ABLATION)
            env["DIFFICULTY"] = diff
            env.pop("DIFFICULTY_OVERRIDES", None)
            env["INCLUDE_ADJ_MATRIX"] = "1"
            env["MODEL_PRETRAINED"] = m.pretrained
            _write_conf(
                name=name,
                description=(
                    f"Ablation: include adjacency list in prompt "
                    f"(n={ADJLIST_DIFF_N}/task, difficulty={diff}) for {m.pretrained}"
                ),
                env=env,
            )
            batches["ablation_adjlist"].append(name)

    # --- Adjacency-list COLORING re-run: special-coloring + adj list ----------
    # The adjacency-list ablation's coloring task MUST use SPECIAL_COLORING:
    # default coloring graphs (full Delaunay) have χ concentrated on 3-4, so the
    # answer is nearly constant and accuracy is dominated by guessing. This batch
    # plants χ uniformly across {2,3,4} (linear 2→3→4) while also injecting the
    # adjacency list into the prompt, so the coloring column of the adj-list
    # ablation is meaningful. Coloring task only; the conn/shortest_path adj-list
    # results live in the `ablation_adjlist` batch.
    batches["ablation_adjlist_coloring"] = []
    for diff in STANDARD_DIFFICULTIES:
        for m in MODELS_4B:
            name = f"graph_bench_ablation_adjlist_coloring_{diff}_{m.short}"
            env = _standard_env(ADJLIST_DIFF_N, CHUNK_ABLATION)
            env["DIFFICULTY"] = diff
            env.pop("DIFFICULTY_OVERRIDES", None)
            env["TASKS"] = "coloring"
            env["SPECIAL_COLORING"] = "1"
            env["INCLUDE_ADJ_MATRIX"] = "1"
            env["MODEL_PRETRAINED"] = m.pretrained
            _write_conf(
                name=name,
                description=(
                    f"Ablation: adjacency list + special-coloring (χ∈{{2,3,4}} "
                    f"uniform), coloring only, n={ADJLIST_DIFF_N}/task, "
                    f"difficulty={diff}) for {m.pretrained}"
                ),
                env=env,
            )
            batches["ablation_adjlist_coloring"].append(name)

    # --- Sweep over nodes: 4B panel, 250 samples per value --------------------
    batches["sweep_nodes"] = []
    for m in MODELS_4B:
        name = f"graph_bench_sweep_nodes_{m.short}"
        env = _standard_env(
            ABLATION_N, CHUNK_SWEEP
        )  # NUM_SAMPLES ignored in sweep mode
        env["MODEL_PRETRAINED"] = m.pretrained
        env["CONSTRAINT"] = "nodes"
        env["CONSTRAINT_VALUES"] = SWEEP_NODE_VALUES
        env["SAMPLES_PER_VALUE"] = str(SWEEP_NODE_SPV)
        # Difficulty overrides don't apply in sweep mode.
        env.pop("DIFFICULTY_OVERRIDES", None)
        _write_conf(
            name=name,
            description=f"Sweep: vertex-count axis ({SWEEP_NODE_VALUES}, {SWEEP_NODE_SPV}/value) for {m.pretrained}",
            env=env,
        )
        batches["sweep_nodes"].append(name)

    # --- Sweep over edges: 4B panel, 100 samples per value --------------------
    batches["sweep_edges"] = []
    for m in MODELS_4B:
        name = f"graph_bench_sweep_edges_{m.short}"
        env = _standard_env(ABLATION_N, CHUNK_SWEEP)
        env["MODEL_PRETRAINED"] = m.pretrained
        env["CONSTRAINT"] = "edges"
        env["CONSTRAINT_VALUES"] = SWEEP_EDGE_VALUES
        env["SAMPLES_PER_VALUE"] = str(SWEEP_EDGE_SPV)
        env.pop("DIFFICULTY_OVERRIDES", None)
        _write_conf(
            name=name,
            description=f"Sweep: edge-count axis ({SWEEP_EDGE_VALUES}, {SWEEP_EDGE_SPV}/value) for {m.pretrained}",
            env=env,
        )
        batches["sweep_edges"].append(name)

    # --- Coloring-only sweeps with balanced χ∈{2,3,4} (special coloring) -------
    # The plain sweeps above run all three tasks; their coloring slice uses the
    # default full-triangulation graphs whose chromatic number concentrates on
    # 3-4 (weak, guessable signal). These re-run the node/edge sweeps for the
    # coloring task ALONE with SPECIAL_COLORING, which plants χ linearly across
    # {2,3,4} per constraint-value bucket (clamped to ≤ node_count on the node
    # axis — a graph can't require more colors than it has nodes). One job per
    # (axis, model). Named graph_bench_sweep_<axis>_coloring_<model> so the
    # batch-report axis parser still classifies them as sweeps.
    for axis, values, spv in (
        ("nodes", SWEEP_NODE_VALUES, SWEEP_NODE_SPV),
        ("edges", SWEEP_EDGE_VALUES, SWEEP_EDGE_SPV),
    ):
        batch = f"sweep_{axis}_coloring"
        batches[batch] = []
        for m in MODELS_4B:
            name = f"graph_bench_sweep_{axis}_coloring_{m.short}"
            env = _standard_env(ABLATION_N, CHUNK_SWEEP)
            env["TASKS"] = "coloring"
            env["SPECIAL_COLORING"] = "1"
            env["MODEL_PRETRAINED"] = m.pretrained
            env["CONSTRAINT"] = axis
            env["CONSTRAINT_VALUES"] = values
            env["SAMPLES_PER_VALUE"] = str(spv)
            env.pop("DIFFICULTY_OVERRIDES", None)
            _write_conf(
                name=name,
                description=(
                    f"Sweep: {axis}-count axis ({values}, {spv}/value), coloring "
                    f"only with balanced χ∈{{2,3,4}} (special-coloring) for {m.pretrained}"
                ),
                env=env,
            )
            batches[batch].append(name)

    # --- Thinking vs no-thinking ablation: difficulty-separated, n=100/task ----
    # Two arms (THINKING=0/1) × 3 difficulties × 3 models. Mirrors the standard
    # per-difficulty split: a coloring-only job (special χ∈{2,3,4}) plus a
    # directed_connectivity+shortest_path job, so all three tasks are covered at
    # n=100/task. The run_eval THINKING flag flips enable_thinking (vllm) / the
    # R1 system prompt (InternVL) and raises max_new_tokens to 4096. The think
    # arm's coloring/conn+sp jobs are the expensive ones (long reasoning).
    think_jobs: list[str] = []
    nothink_jobs: list[str] = []
    for mode, thinking in (("nothink", "0"), ("think", "1")):
        bucket = think_jobs if thinking == "1" else nothink_jobs
        chunk = CHUNK_THINK if thinking == "1" else CHUNK_ABLATION
        for diff in STANDARD_DIFFICULTIES:
            for m in THINK_MODELS:
                # coloring only, balanced χ∈{2,3,4} (special coloring)
                cname = f"graph_bench_think_{mode}_coloring_{diff}_{m.short}"
                cenv = _standard_env(THINK_ABLATION_N, chunk)
                cenv["DIFFICULTY"] = diff
                cenv.pop("DIFFICULTY_OVERRIDES", None)
                cenv["TASKS"] = "coloring"
                cenv["SPECIAL_COLORING"] = "1"
                cenv["THINKING"] = thinking
                cenv["MODEL_PRETRAINED"] = m.pretrained
                # InternVL runs through vllm for the ablation (batched/fast, and
                # temperature actually applies — the HF wrapper silently drops it).
                # Its R1 thinking is set by run_eval via system_prompt=internvl_r1.
                # Both arms use vllm so they differ only by thinking; Gemma already
                # maps to vllm.
                if m.short == "internvl35_4b":
                    cenv["MODEL_NAME_OVERRIDE"] = "vllm"
                    cenv["INTERNVL_R1_VARIANT"] = "internvl_r1_v1"  # commit-rule R1 (0% trunc, best acc)
                _write_conf(
                    name=cname,
                    description=(
                        f"Thinking ablation ({mode}): coloring only, balanced "
                        f"χ∈{{2,3,4}} (special-coloring), n={THINK_ABLATION_N}/task, "
                        f"difficulty={diff} for {m.pretrained}"
                    ),
                    env=cenv,
                )
                bucket.append(cname)
                # directed_connectivity + shortest_path
                name = f"graph_bench_think_{mode}_{diff}_{m.short}"
                env = _standard_env(THINK_ABLATION_N, chunk)
                env["DIFFICULTY"] = diff
                env.pop("DIFFICULTY_OVERRIDES", None)
                env["TASKS"] = "directed_connectivity shortest_path"
                env["THINKING"] = thinking
                env["MODEL_PRETRAINED"] = m.pretrained
                if m.short == "internvl35_4b":
                    env["MODEL_NAME_OVERRIDE"] = "vllm"
                    env["INTERNVL_R1_VARIANT"] = "internvl_r1_v1"  # commit-rule R1 (0% trunc, best acc)
                _write_conf(
                    name=name,
                    description=(
                        f"Thinking ablation ({mode}): directed_connectivity + "
                        f"shortest_path, n={THINK_ABLATION_N}/task, difficulty={diff} "
                        f"for {m.pretrained}"
                    ),
                    env=env,
                )
                bucket.append(name)

    batches["think_ablation"] = think_jobs + nothink_jobs
    # Split across the two eval VMs. Interleave *within* each arm so vm02 and
    # vm03 each get ~half the (slow) think jobs and ~half the no-think jobs —
    # balance by cost, not job count.
    batches["think_ablation_vm02"] = think_jobs[0::2] + nothink_jobs[0::2]
    batches["think_ablation_vm03"] = think_jobs[1::2] + nothink_jobs[1::2]

    # --- Thinking × adjacency-list combined ablation --------------------------
    # Crosses the two ablation axes: run the *entire, already-proven* thinking
    # ablation (both arms, 3 models, 3 difficulties, all tasks, the per-model
    # think mechanism + fp8/budget tuning that live in run_eval.sh) but ALSO
    # inject the text adjacency list into the prompt (INCLUDE_ADJ_MATRIX=1). The
    # only difference from graph_bench_think_* is the adjacency-list prompt, so
    # the think-vs-nothink effect stays directly comparable to the image-only
    # thinking ablation, and thinkadj-vs-think isolates the adjacency effect.
    def _emit_thinkadj(job_prefix, num_samples, thinking_chunk, difficulties, smoke):
        think_j: list[str] = []
        nothink_j: list[str] = []
        for mode, thinking in (("nothink", "0"), ("think", "1")):
            bucket = think_j if thinking == "1" else nothink_j
            chunk = thinking_chunk if thinking == "1" else CHUNK_ABLATION
            for diff in difficulties:
                for m in THINK_MODELS:
                    for tasks, special, infix in (
                        ("coloring", True, "coloring_"),
                        ("directed_connectivity shortest_path", False, ""),
                    ):
                        name = f"{job_prefix}_{mode}_{infix}{diff}_{m.short}"
                        env = _standard_env(num_samples, chunk)
                        env["DIFFICULTY"] = diff
                        env.pop("DIFFICULTY_OVERRIDES", None)
                        env["TASKS"] = tasks
                        if special:
                            env["SPECIAL_COLORING"] = "1"
                        env["INCLUDE_ADJ_MATRIX"] = "1"
                        env["THINKING"] = thinking
                        env["MODEL_PRETRAINED"] = m.pretrained
                        # Mirror the pure thinking ablation exactly: InternVL runs
                        # through vllm with the commit-rule R1 preset (0% trunc).
                        if m.short == "internvl35_4b":
                            env["MODEL_NAME_OVERRIDE"] = "vllm"
                            env["INTERNVL_R1_VARIANT"] = "internvl_r1_v1"
                        tasklabel = (
                            "coloring only (special-coloring χ∈{2,3,4} uniform)"
                            if special else "directed_connectivity + shortest_path"
                        )
                        _write_conf(
                            name=name,
                            description=(
                                f"Thinking×adjacency-list ablation ({mode}"
                                f"{', SMOKE' if smoke else ''}): {tasklabel}, "
                                f"adjacency list injected in prompt, "
                                f"n={num_samples}/task, difficulty={diff} "
                                f"for {m.pretrained}"
                            ),
                            env=env,
                        )
                        bucket.append(name)
        return think_j, nothink_j

    # Full combined ablation: 2 arms × 3 diff × 3 models × 2 job-types = 36 jobs,
    # n=100/task. Same cost-balanced VM interleave as the pure thinking ablation.
    ta_think, ta_nothink = _emit_thinkadj(
        "graph_bench_thinkadj", THINK_ABLATION_N, CHUNK_THINK,
        STANDARD_DIFFICULTIES, smoke=False,
    )
    batches["thinkadj_ablation"] = ta_think + ta_nothink
    batches["thinkadj_ablation_vm02"] = ta_think[0::2] + ta_nothink[0::2]
    batches["thinkadj_ablation_vm03"] = ta_think[1::2] + ta_nothink[1::2]

    # Smoke gate: hard only (worst case for prompt length + over-deliberation),
    # n=10, both arms, all 3 models, both job-types = 12 jobs. Confirms before
    # the multi-hour full run that (a) the adjacency list is injected alongside
    # thinking, (b) the longer prompt doesn't OOM the 12 GiB card, (c) reasoning
    # still closes (Qwen native budget) with ~0 truncation, (d) the answer stays
    # isolated from the adjacency-list integers. Split 6/6 across the two VMs.
    sm_think, sm_nothink = _emit_thinkadj(
        "graph_bench_thinkadjsmoke", 10, CHUNK_THINK, ("hard",), smoke=True,
    )
    batches["thinkadj_smoke"] = sm_think + sm_nothink
    batches["thinkadj_smoke_vm02"] = sm_think[0::2] + sm_nothink[0::2]
    batches["thinkadj_smoke_vm03"] = sm_think[1::2] + sm_nothink[1::2]

    # --- Combined difficulty-separated ablation batch -------------------------
    # labels(letters+none) + node-color, difficulty-separated, n=100/task, all
    # three tasks (coloring via special χ∈{2,3,4}). This is the single manifest
    # to hand to run_batch.sh for the full campaign.
    batches["ablation_labels_color_100"] = (
        list(batches["ablation_labels"]) + list(batches["ablation_color"])
    )

    # --- Emit batch manifests -------------------------------------------------
    # load_job() takes the conf path *relative to jobs/* without the .conf
    # suffix, so for confs in graph_benchmark/ the job id is
    # "graph_benchmark/<name>".
    total = 0
    for batch_name, job_names in batches.items():
        manifest = _BATCH_DIR / f"{batch_name}.txt"
        manifest.write_text(
            "\n".join(f"graph_benchmark/{n}" for n in job_names) + "\n",
            encoding="utf-8",
            newline="\n",
        )
        total += len(job_names)
        print(f"[batch] {batch_name}: {len(job_names)} jobs -> {manifest}")

    print(
        f"\nWrote {total} conf files under {_OUT_DIR}/ and "
        f"{len(batches)} batch manifests under {_BATCH_DIR}/."
    )


if __name__ == "__main__":
    main()
