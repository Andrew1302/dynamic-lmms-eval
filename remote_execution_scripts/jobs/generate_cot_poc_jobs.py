"""Emit the CoT experiment jobs.

Every run is listed literally in RUNS below - model, task, sample window, and the
exact prompt id of each arm. Nothing is inferred, so reading RUNS tells you
exactly what will execute.

    python remote_execution_scripts/jobs/generate_cot_poc_jobs.py

Why seed 42: it is what every published campaign used (run_eval.sh defaults
SEED=42 and no conf overrides it).

Why increments are safe to pool. A sample's seed is
``seed + index*1000 + crc32(task)%1000`` -- it depends only on the seed, the
global index and the task name, never on how many samples were requested. So
``--start-index 50 --num-samples 50`` regenerates nothing and yields exactly
samples 50..99, which pool with an earlier 0..49 run. Verified empirically: the
n=2 smoke dataset and the first two rows of the n=50 dataset agree on id,
answer, prompt hash, image hash and graph size.

The few-shot arms always pin the *direct* (plain-graph) exemplar, for the
disguised questions too. That is the point of the arm: it probes whether the
method transfers across the framing, so it must not be made variant-matched.
"""

from __future__ import annotations

import argparse
import dataclasses
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT_DIR = HERE / "cot_poc"
BATCH_DIR = HERE.parent / "batches"

SEED = 42
DIFFICULTY = "medium"

MODELS = {
    "qwen35_2b": "Qwen/Qwen3.5-2B",
    "qwen35_4b": "Qwen/Qwen3.5-4B",
}

LMMS_TASK = {"sp": "shortest_path", "coloring": "coloring", "conn": "directed_connectivity"}


@dataclasses.dataclass(frozen=True)
class Run:
    model: str  # key into MODELS
    task: str  # key into LMMS_TASK; also the job-name marker (_families._CTASK)
    start: int
    n: int
    arms: tuple[str, ...]  # prompt ids, in order: control, zero-shot, few-shot, extras
    inc: bool = False  # True -> "cottinc_" prefix, filed as a *_inc leaf


# The standard three arms. The few-shot id differs per task because the exemplar
# is task-specific; the zero-shot id differs because each task needs its own
# method. direct_v1 is the shared, golden-pinned control.
SP = ("direct_v1", "sp_explain_v1", "sp_fewshot_direct_ex1_v1")
COL = ("direct_v1", "col_explain_v1", "col_fewshot_direct_ex1_v1")
CONN = ("direct_v1", "conn_explain_v2", "conn_fewshot_direct_ex1_v1")

RUNS: tuple[Run, ...] = (
    # ---- Qwen3.5-2B ---------------------------------------------------------
    # sp already has 0..49 on disk under the older "cot_" job names.
    Run("qwen35_2b", "sp", 50, 50, SP, inc=True),
    Run("qwen35_2b", "coloring", 0, 100, COL),
    # conn on the 2B carries two extra arms that the 4B cannot run: a revised
    # method prompt, and a two-exemplar (Yes + No) few-shot arm whose 3-image
    # prompt needs a 32768 window. The 4B's KV cache is 30,096 tokens.
    Run("qwen35_2b", "conn", 0, 100,
        CONN + ("conn_explain_v3", "conn_fewshot_direct_ex12_v1")),
    # ---- Qwen3.5-4B ---------------------------------------------------------
    # Same three arms per task, same samples, so the two models are comparable.
    Run("qwen35_4b", "sp", 0, 100, SP),
    Run("qwen35_4b", "coloring", 0, 100, COL),
    Run("qwen35_4b", "conn", 0, 100, CONN),
)

CONF = """\
# =============================================================================
# Generated by remote_execution_scripts/jobs/generate_cot_poc_jobs.py
# Do not edit by hand - re-run the generator instead.
# =============================================================================
# Prompt text: prompting/library/{prompt_id}.yaml
#   inspect with: python -m prompting.show {prompt_id} --task {lmms_task} --variant disguise
# Samples {start}..{last} of the seed-{seed} stream ({n} per variant).
JOB_NAME="{job}"
DATASET_DIR="{dataset_dir}"
export CAMPAIGN="18_abl_cot"
export SEED="{seed}"
export NUM_SAMPLES="{n}"
export START_INDEX="{start}"
export DIFFICULTY="{difficulty}"
export TASKS="{lmms_task}"
export PROMPT_ID="{prompt_id}"
export MODEL_PRETRAINED="{model}"
export CHUNK_SIZE="{chunk}"
export DATASET_DIR
export JOB_NAME

UPLOAD_PATHS=(
    "lmms_eval"
    "prompting"
    "tools"
    "examples/models/dynamic_graph_benchmark"
    "pyproject.toml"
    "uv.lock"
    "setup.py"
    "README.md"
)

DATASET_UPLOAD_PATHS=(
    "src"
    "pyproject.toml"
    "uv.lock"
)

REMOTE_SETUP_CMD="uv sync && uv pip install adjustText cartopy"

REMOTE_RUN_CMD="bash examples/models/dynamic_graph_benchmark/run_eval.sh"

RESULT_PATHS=(
    "logs/${{JOB_NAME}}"
)

COMPARE_PAIRS=(
    "{lmms_task}:dynamic_graph_benchmark_{lmms_task}_direct:dynamic_graph_benchmark_{lmms_task}_disguise"
)
"""


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.parse_args(argv)

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    BATCH_DIR.mkdir(parents=True, exist_ok=True)

    total = 0
    for run in RUNS:
        lmms_task = LMMS_TASK[run.task]
        # One dataset per (task, window). Every arm of a run shares it, so any
        # difference between arms is the prompt and nothing else. Models share it
        # too, so the two panels see identical graphs.
        dataset_dir = f"./dataset_cot_{run.task}_{DIFFICULTY}_s{run.start}_n{run.n}"
        prefix = "cottinc" if run.inc else "cott"
        jobs = []
        for prompt_id in run.arms:
            job = f"graph_bench_{prefix}_{run.task}_{prompt_id}_{DIFFICULTY}_{run.model}"
            (OUT_DIR / f"{job}.conf").write_text(
                CONF.format(
                    job=job, prompt_id=prompt_id, lmms_task=lmms_task, dataset_dir=dataset_dir,
                    seed=SEED, n=run.n, start=run.start, last=run.start + run.n - 1,
                    difficulty=DIFFICULTY, model=MODELS[run.model], chunk=min(run.n, 50),
                ),
                encoding="utf-8", newline="\n",
            )
            jobs.append(f"cot_poc/{job}")
            total += 1

        tag = f"cot_{run.model}_{run.task}_s{run.start}n{run.n}"
        (BATCH_DIR / f"{tag}.txt").write_text("\n".join(jobs) + "\n", encoding="utf-8", newline="\n")
        print(f"  {tag:34} samples {run.start}..{run.start + run.n - 1}  ({len(jobs)} arms)")

    # One manifest per model, so a whole panel can be dispatched in one call.
    for model in MODELS:
        model_jobs = [
            f"cot_poc/graph_bench_{'cottinc' if r.inc else 'cott'}_{r.task}_{p}_{DIFFICULTY}_{r.model}"
            for r in RUNS if r.model == model for p in r.arms
        ]
        (BATCH_DIR / f"cot_panel_{model}.txt").write_text("\n".join(model_jobs) + "\n", encoding="utf-8", newline="\n")
        print(f"  cot_panel_{model}.txt -> {len(model_jobs)} jobs")

    print(f"\n{total} job confs   seed={SEED} difficulty={DIFFICULTY}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
