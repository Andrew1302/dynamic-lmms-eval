"""Emit the CoT proof-of-concept jobs.

One experiment, three arms, one task. Everything that defines the experiment is
in EXPERIMENT below, so the seed and sample count cannot drift between arms.

    python remote_execution_scripts/jobs/generate_cot_poc_jobs.py              # n=50 run
    python remote_execution_scripts/jobs/generate_cot_poc_jobs.py --samples 2 --prefix cotpoc_smoke

Why seed 42: it is what every published campaign used (run_eval.sh defaults
SEED=42 and no conf overrides it). A sample's seed is
``seed + index*1000 + crc32(task)%1000`` -- it depends only on the seed, the
global index and the task name, NOT on which other tasks were requested. So
these 50 shortest_path/medium graphs are exactly the first 50 of the published
standard_medium run, and the control arm is directly comparable to it.
"""

from __future__ import annotations

import argparse
import dataclasses
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT_DIR = HERE / "cot_poc"
BATCH_DIR = HERE.parent / "batches"


@dataclasses.dataclass(frozen=True)
class Experiment:
    seed: int = 42  # pinned: matches every published campaign
    samples: int = 50  # per variant, so 2 x this many rows per arm
    difficulty: str = "medium"
    tasks: str = "shortest_path"
    model: str = "Qwen/Qwen3.5-4B"  # the panel model, so the control is comparable
    model_short: str = "qwen35_4b"
    chunk_size: int = 50  # resumable: a CoT arm is slow enough to be worth it


@dataclasses.dataclass(frozen=True)
class Arm:
    prompt_id: str
    note: str


ARMS = (
    Arm("direct_v1", "control: the unchanged terse baseline"),
    Arm("sp_fewshot_direct_ex1_v1", "one PLAIN-GRAPH worked example, used for both variants (cross-domain probe)"),
    Arm("sp_explain_v1", "zero-shot, explicit shortest-path method, identical text for both variants"),
)

CONF = """\
# =============================================================================
# Generated by remote_execution_scripts/jobs/generate_cot_poc_jobs.py
# Do not edit by hand - re-run the generator instead.
# =============================================================================
# CoT PoC arm: {note}
# Prompt text: prompting/library/{prompt_id}.yaml
#   inspect with: python -m prompting.show {prompt_id} --variant disguise
JOB_NAME="{job}"
DATASET_DIR="{dataset_dir}"
export CAMPAIGN="18_abl_cot"
export SEED="{seed}"
export NUM_SAMPLES="{samples}"
export DIFFICULTY="{difficulty}"
export TASKS="{tasks}"
export PROMPT_ID="{prompt_id}"
export MODEL_PRETRAINED="{model}"
export CHUNK_SIZE="{chunk}"
export DATASET_DIR
export JOB_NAME

UPLOAD_PATHS=(
    "lmms_eval"
    "prompting"
    "tools"
    "examples/models/dynamic_graph_benchmark"
    "pyproject.toml"
    "uv.lock"
    "setup.py"
    "README.md"
)

DATASET_UPLOAD_PATHS=(
    "src"
    "pyproject.toml"
    "uv.lock"
)

REMOTE_SETUP_CMD="uv sync && uv pip install adjustText cartopy"

REMOTE_RUN_CMD="bash examples/models/dynamic_graph_benchmark/run_eval.sh"

RESULT_PATHS=(
    "logs/${{JOB_NAME}}"
)

COMPARE_PAIRS=(
    "shortest_path:dynamic_graph_benchmark_shortest_path_direct:dynamic_graph_benchmark_shortest_path_disguise"
)
"""


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--samples", type=int, default=Experiment.samples)
    ap.add_argument("--prefix", default="cotpoc")
    args = ap.parse_args(argv)

    exp = dataclasses.replace(Experiment(), samples=args.samples)
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    BATCH_DIR.mkdir(parents=True, exist_ok=True)

    # All arms share one dataset: identical graphs, so any difference between
    # arms is the prompt. prepare is a fingerprint no-op after the first arm.
    dataset_dir = f"./dataset_{args.prefix}_{exp.difficulty}_n{exp.samples}"

    jobs = []
    for arm in ARMS:
        job = f"graph_bench_cot_{arm.prompt_id}_{exp.difficulty}_{exp.model_short}"
        if args.prefix != "cotpoc":
            job = f"{job}__{args.prefix}"
        path = OUT_DIR / f"{job}.conf"
        path.write_text(
            CONF.format(
                job=job,
                note=arm.note,
                prompt_id=arm.prompt_id,
                dataset_dir=dataset_dir,
                seed=exp.seed,
                samples=exp.samples,
                difficulty=exp.difficulty,
                tasks=exp.tasks,
                model=exp.model,
                chunk=exp.chunk_size,
            ),
            encoding="utf-8",
            newline="\n",
        )
        jobs.append(f"cot_poc/{job}")
        print(f"  {job}")

    (BATCH_DIR / f"{args.prefix}.txt").write_text("\n".join(jobs) + "\n", encoding="utf-8", newline="\n")
    # Cost-balanced split: the two CoT arms generate ~20x the tokens of the
    # control, so they go to different boxes and the cheap control rides along.
    (BATCH_DIR / f"{args.prefix}_vm03.txt").write_text("\n".join([jobs[0], jobs[2]]) + "\n", encoding="utf-8", newline="\n")
    (BATCH_DIR / f"{args.prefix}_vm02.txt").write_text(jobs[1] + "\n", encoding="utf-8", newline="\n")

    rows = exp.samples * 2
    print(f"\n{len(jobs)} arms x {rows} rows ({exp.samples}/variant) = {len(jobs) * rows} generations")
    print(f"seed={exp.seed} difficulty={exp.difficulty} task={exp.tasks} model={exp.model}")
    print(f"manifests: {args.prefix}.txt, {args.prefix}_vm03.txt (control + explain), {args.prefix}_vm02.txt (few-shot)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
